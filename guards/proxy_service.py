#!/usr/bin/env python3
"""
proxy_service.py: run the Databricks metadata proxy automatically at login.

  macOS   -> a launchd LaunchAgent  (~/Library/LaunchAgents/com.databricks-guard.proxy.plist)
  Windows -> a Task Scheduler task  ("DatabricksGuardProxy", runs hidden at logon, restarts on failure)

Both run as YOU, inside your logged-in session, so they can use your OAuth U2M login
(macOS Keychain / Windows Credential Manager, via `databricks auth token`).

  python3 proxy_service.py install   --upstream-profile DEFAULT [--port 8787]
  python3 proxy_service.py status            # running? acting as whom?
  python3 proxy_service.py restart
  python3 proxy_service.py uninstall
  python3 proxy_service.py doctor            # end-to-end self-test of hooks + proxy on this machine

Everything lives in ~/.databricks-guard/:
  bin/                 copies of the proxy and guard (outside any repo)
  proxy-config.json    profile, port, paths
  proxy.jsonl          the local audit log (every request the agent made)
  proxy-service.log    service stdout/stderr
Standard library only.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import plistlib
import shutil
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import List, Optional
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
LABEL = "com.databricks-guard.proxy"
TASK = "DatabricksGuardProxy"


def user_dir() -> Path:
    return Path(os.environ.get("DBX_GUARD_HOME") or Path.home()) / ".databricks-guard"


def paths() -> dict:
    d = user_dir()
    return {"dir": d, "bin": d / "bin", "config": d / "proxy-config.json", "log": d / "proxy.jsonl",
            "svc_log": d / "proxy-service.log", "launcher": d / "bin" / "run_proxy.py",
            "plist": Path(os.environ.get("DBX_GUARD_HOME") or Path.home()) / "Library" / "LaunchAgents"
            / f"{LABEL}.plist",
            "task_xml": d / "task.xml"}


def system() -> str:
    return os.environ.get("DBX_GUARD_FORCE_OS") or platform.system()   # "Darwin" | "Windows" | "Linux"


def _is_ours(cmd: str) -> bool:
    """Recognise hooks written by this installer (also with Windows 8.3 short names)."""
    c = cmd.lower()
    return "databricks_guard" in c or ("hook --agent" in c and "databr" in c)


def run(cmd: List[str], dry: bool, check: bool = False) -> subprocess.CompletedProcess:
    if dry:
        print("  [dry-run] " + " ".join(cmd))
        return subprocess.CompletedProcess(cmd, 0, "", "")
    return subprocess.run(cmd, capture_output=True, text=True, check=check)


# --------------------------------------------------------------------------------------
# Files shared by both platforms
# --------------------------------------------------------------------------------------
LAUNCHER = r'''# Generated by proxy_service.py: starts the Databricks metadata proxy for the login service.
import json, os, runpy, sys
from pathlib import Path
CFG = Path(__file__).resolve().parent.parent / "proxy-config.json"
cfg = json.loads(CFG.read_text())
extra = [p for p in cfg.get("path_prepend", []) if p]
os.environ["PATH"] = os.pathsep.join(extra + [os.environ.get("PATH", "")])
if cfg.get("config_file"):
    os.environ["DATABRICKS_CONFIG_FILE"] = cfg["config_file"]
if sys.stdout is None or sys.stderr is None or not sys.stderr.isatty():
    log = open(cfg["service_log"], "a", buffering=1, encoding="utf-8")   # pythonw has no console
    sys.stdout = sys.stderr = log
proxy = str(Path(__file__).resolve().parent / "dbx_metadata_proxy.py")
sys.argv = [proxy, "--upstream-profile", cfg["upstream_profile"], "--port", str(cfg["port"]),
            "--log", cfg["log"], "--lenient-start"]
runpy.run_path(proxy, run_name="__main__")
'''


def install_files(upstream_profile: str, port: int, python: str) -> dict:
    p = paths()
    p["bin"].mkdir(parents=True, exist_ok=True)
    for name in ("dbx_metadata_proxy.py", "databricks_guard.py", "proxy_service.py"):
        src = HERE / name
        if src.is_file():
            shutil.copy2(src, p["bin"] / name)
    p["launcher"].write_text(LAUNCHER, encoding="utf-8")

    cli = shutil.which("databricks")
    prepend = [str(Path(cli).parent)] if cli else []
    if system() == "Darwin":
        prepend += ["/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin"]
    elif system() == "Windows":
        la = os.environ.get("LOCALAPPDATA", "")
        prepend += [str(Path(la) / "Microsoft" / "WinGet" / "Links")] if la else []
    cfg = {"upstream_profile": upstream_profile, "port": port, "python": python,
           "log": str(p["log"]), "service_log": str(p["svc_log"]),
           "path_prepend": list(dict.fromkeys(prepend)),
           "config_file": os.environ.get("DATABRICKS_CONFIG_FILE", ""),
           "databricks_cli": cli or ""}
    p["config"].write_text(json.dumps(cfg, indent=2), encoding="utf-8")
    if not cli:
        print("  warning: `databricks` CLI not found on PATH. OAuth U2M needs it; install it, then "
              "re-run install.")
    return cfg


def windowless_python(python: str) -> str:
    """On Windows prefer pythonw.exe so no console window appears at logon."""
    pw = Path(python).with_name("pythonw.exe")
    return str(pw) if pw.is_file() else python


# --------------------------------------------------------------------------------------
# macOS: launchd LaunchAgent
# --------------------------------------------------------------------------------------
def mac_plist(cfg: dict) -> bytes:
    p = paths()
    return plistlib.dumps({
        "Label": LABEL,
        "ProgramArguments": [cfg["python"], str(p["launcher"])],
        "RunAtLoad": True,
        "KeepAlive": True,               # restart if it stops
        "ThrottleInterval": 30,
        "ProcessType": "Background",
        "WorkingDirectory": str(p["dir"]),
        "StandardOutPath": str(p["svc_log"]),
        "StandardErrorPath": str(p["svc_log"]),
        "EnvironmentVariables": {"PATH": ":".join(cfg["path_prepend"])},
    })


def mac_install(cfg: dict, dry: bool) -> None:
    p = paths()
    p["plist"].parent.mkdir(parents=True, exist_ok=True)
    p["plist"].write_bytes(mac_plist(cfg))
    uid = str(os.getuid()) if hasattr(os, "getuid") else "501"
    run(["launchctl", "bootout", f"gui/{uid}/{LABEL}"], dry)            # ignore "not loaded"
    r = run(["launchctl", "bootstrap", f"gui/{uid}", str(p["plist"])], dry)
    if r.returncode != 0:                                                 # older macOS
        run(["launchctl", "load", "-w", str(p["plist"])], dry)


def mac_uninstall(dry: bool) -> None:
    p = paths()
    uid = str(os.getuid()) if hasattr(os, "getuid") else "501"
    run(["launchctl", "bootout", f"gui/{uid}/{LABEL}"], dry)
    if p["plist"].exists() and not dry:
        p["plist"].unlink()


def mac_registered() -> Optional[bool]:
    if shutil.which("launchctl") is None:
        return None
    uid = str(os.getuid())
    return run(["launchctl", "print", f"gui/{uid}/{LABEL}"], False).returncode == 0


# --------------------------------------------------------------------------------------
# Windows: Task Scheduler (XML so we get restart-on-failure and no time limit)
# --------------------------------------------------------------------------------------
def win_user() -> str:
    dom, usr = os.environ.get("USERDOMAIN", ""), os.environ.get("USERNAME", "")
    return f"{dom}\\{usr}" if dom else usr


def win_task_xml(cfg: dict) -> str:
    p = paths()
    user = escape(win_user())
    cmd = escape(windowless_python(cfg["python"]))
    arg = escape(f'"{p["launcher"]}"')
    return f'''<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>Databricks metadata-only proxy for coding agents (databricks-guard)</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger><Enabled>true</Enabled><UserId>{user}</UserId></LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>{user}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings><StopOnIdleEnd>false</StopOnIdleEnd><RestartOnIdle>false</RestartOnIdle></IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>true</Hidden>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{cmd}</Command>
      <Arguments>{arg}</Arguments>
      <WorkingDirectory>{escape(str(p["dir"]))}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
'''


def win_install(cfg: dict, dry: bool) -> None:
    p = paths()
    p["task_xml"].write_text(win_task_xml(cfg), encoding="utf-16")
    run(["schtasks", "/End", "/TN", TASK], dry)
    r = run(["schtasks", "/Create", "/TN", TASK, "/XML", str(p["task_xml"]), "/F"], dry)
    if r.returncode != 0:
        raise SystemExit(f"schtasks /Create failed: {r.stderr or r.stdout}")
    run(["schtasks", "/Run", "/TN", TASK], dry)


def win_uninstall(dry: bool) -> None:
    run(["schtasks", "/End", "/TN", TASK], dry)
    run(["schtasks", "/Delete", "/TN", TASK, "/F"], dry)


def win_registered() -> Optional[bool]:
    if shutil.which("schtasks") is None:
        return None
    return run(["schtasks", "/Query", "/TN", TASK], False).returncode == 0


