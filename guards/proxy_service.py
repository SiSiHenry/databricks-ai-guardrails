# Status / health
# --------------------------------------------------------------------------------------
def port_open(port: int) -> bool:
    with socket.socket() as s:
        s.settimeout(1)
        return s.connect_ex(("127.0.0.1", port)) == 0


def proxy_identity(port: int) -> str:
    """Ask the proxy who it acts as (SCIM Me is on the proxy's allowlist)."""
    req = urllib.request.Request(f"http://127.0.0.1:{port}/api/2.0/preview/scim/v2/Me",
                                 headers={"Authorization": "Bearer local-proxy-placeholder"})
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            me = json.loads(r.read() or b"{}")
        return me.get("userName") or me.get("displayName") or "unknown"
    except urllib.error.HTTPError as e:
        try:
            return f"error {e.code}: {json.loads(e.read()).get('message', '')[:160]}"
        except Exception:
            return f"error {e.code}"
    except Exception as e:
        return f"error: {e}"


def load_cfg() -> dict:
    p = paths()
    if not p["config"].is_file():
        raise SystemExit("not installed (no ~/.databricks-guard/proxy-config.json). Run: install")
    return json.loads(p["config"].read_text(encoding="utf-8"))


def cmd_status(_args) -> int:
    cfg = load_cfg()
    p = paths()
    osname = system()
    reg = mac_registered() if osname == "Darwin" else win_registered() if osname == "Windows" else None
    up = port_open(cfg["port"])
    print(f"Databricks metadata proxy ({osname})")
    print(f"  login service : {'registered' if reg else 'NOT registered' if reg is False else 'n/a'}")
    print(f"  listening     : {'yes' if up else 'NO'} on http://127.0.0.1:{cfg['port']}")
    print(f"  upstream      : profile [{cfg['upstream_profile']}]")
    if up:
        print(f"  acting as     : {proxy_identity(cfg['port'])}")
    print(f"  audit log     : {p['log']}")
    print(f"  service log   : {p['svc_log']}")
    if not up and p["svc_log"].is_file():
        tail = p["svc_log"].read_text(encoding="utf-8", errors="replace").splitlines()[-8:]
        print("  last service log lines:\n    " + "\n    ".join(tail))
    return 0 if up else 1


def wait_for(port: int, seconds: float = 15) -> bool:
    end = time.time() + seconds
    while time.time() < end:
        if port_open(port):
            return True
        time.sleep(0.5)
    return False


def cmd_install(args, cfg: Optional[dict] = None) -> int:
    osname = system()
    if osname not in ("Darwin", "Windows"):
        print(f"Autostart supports macOS and Windows; on {osname} run the proxy manually:\n"
              f"  python3 {HERE / 'dbx_metadata_proxy.py'} --upstream-profile {args.upstream_profile}")
        return 1
    python = args.python or sys.executable
    cfg = cfg or install_files(args.upstream_profile, args.port, python)
    print(f"Installing login service for the metadata proxy ({osname}) ...")
    (mac_install if osname == "Darwin" else win_install)(cfg, args.dry_run)
    if args.dry_run:
        return 0
    if wait_for(args.port):
        print(f"  running on http://127.0.0.1:{args.port}, acting as: {proxy_identity(args.port)}")
        return 0
    print("  service registered but not listening yet. Check: python3 proxy_service.py status")
    return 1


def cmd_uninstall(args) -> int:
    osname = system()
    (mac_uninstall if osname == "Darwin" else win_uninstall)(args.dry_run)
    print("Login service removed (logs kept in ~/.databricks-guard/).")
    return 0


def cmd_restart(args) -> int:
    cfg = load_cfg()
    osname = system()
    if osname == "Darwin":
        uid = str(os.getuid())
        run(["launchctl", "kickstart", "-k", f"gui/{uid}/{LABEL}"], args.dry_run)
    else:
        run(["schtasks", "/End", "/TN", TASK], args.dry_run)
        run(["schtasks", "/Run", "/TN", TASK], args.dry_run)
    if not args.dry_run and wait_for(cfg["port"]):
        print(f"restarted; acting as: {proxy_identity(cfg['port'])}")
    return 0


# --------------------------------------------------------------------------------------
# doctor: deterministic end-to-end self-test on this machine
# --------------------------------------------------------------------------------------
def _hook_commands() -> List[tuple]:
    home = Path(os.environ.get("DBX_GUARD_HOME") or Path.home())
    found = []
    for agent, f, key in (("claude", home / ".claude" / "settings.json", "PreToolUse"),
                          ("cursor", home / ".cursor" / "hooks.json", "beforeShellExecution")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        entries = data.get("hooks", {}).get(key, [])
        for e in entries:
            cmds = [h.get("command", "") for h in e.get("hooks", [])] if agent == "claude" else [e.get("command", "")]
            for c in cmds:
                if _is_ours(c):
                    found.append((agent, c))
    return found


def _shells() -> List[List[str]]:
    if system() == "Windows":
        out = [["cmd", "/c"]]
        for ps in ("powershell", "pwsh"):
            if shutil.which(ps):
                out.append([ps, "-NoProfile", "-Command"])
        gb = shutil.which("bash")
        if gb:
            out.append([gb, "-c"])
        return out
    return [[s, "-c"] for s in ("/bin/sh", "/bin/zsh", "/bin/bash") if Path(s).exists()]


def cmd_doctor(_args) -> int:
    ok = True
    print("1) Hook commands run and block a SQL query in every shell on this machine")
    hooks = _hook_commands()
    if not hooks:
        print("   FAIL no user-level hooks found (~/.claude/settings.json, ~/.cursor/hooks.json). "
              "Run install.py.")
        ok = False
    deny_payload = {"claude": {"tool_name": "Bash", "tool_input": {"command": "databricks sql query 'select 1'"}},
                    "cursor": {"hook_event_name": "beforeShellExecution",
                               "command": "databricks sql query 'select 1'"}}
    allow_payload = {"claude": {"tool_name": "Bash", "tool_input": {"command": "git status"}},
                     "cursor": {"hook_event_name": "beforeShellExecution", "command": "git status"}}
    env = dict(os.environ, DBX_GUARD_NO_LOG="1")
    for agent, c in hooks:
        shells = _shells()
        if system() == "Windows":   # test each hook in the shell its app really uses
            want = ("powershell", "pwsh") if agent == "cursor" else ("bash", "cmd")
            shells = [sh for sh in shells if Path(sh[0]).stem.lower() in want] or shells
        for sh in shells:
            name = Path(sh[0]).name
            try:
                d = subprocess.run(sh + [c], input=json.dumps(deny_payload[agent]), capture_output=True,
                                   text=True, timeout=60, env=env)
                a = subprocess.run(sh + [c], input=json.dumps(allow_payload[agent]), capture_output=True,
                                   text=True, timeout=60, env=env)
            except Exception as e:
                print(f"   FAIL {agent:6s} via {name}: {e}")
                ok = False
                continue
            good = d.returncode == 2 and a.returncode == 0
            if agent == "cursor":
                good = good and '"deny"' in d.stdout and '"allow"' in a.stdout
            print(f"   {'ok  ' if good else 'FAIL'} {agent:6s} via {name:10s} (deny exit={d.returncode}, "
                  f"allow exit={a.returncode})")
            if not good:
                ok = False
                print("        " + (d.stderr or d.stdout).strip()[:300].replace("\n", "\n        "))

    print("2) Metadata proxy")
    try:
        cfg = load_cfg()
        if port_open(cfg["port"]):
            who = proxy_identity(cfg["port"])
            good = not who.startswith("error")
            print(f"   {'ok  ' if good else 'FAIL'} listening on {cfg['port']}, acting as: {who}")
            ok &= good
            req = urllib.request.Request(f"http://127.0.0.1:{cfg['port']}/api/2.0/sql/statements",
                                         data=b"{}", method="POST")
            try:
                urllib.request.urlopen(req, timeout=10)
                print("   FAIL proxy forwarded a SQL statement request")
                ok = False
            except urllib.error.HTTPError as e:
                print(f"   {'ok  ' if e.code == 403 else 'FAIL'} SQL statement request refused ({e.code})")
                ok &= e.code == 403
        else:
            print(f"   FAIL not listening on {cfg['port']} (python3 proxy_service.py status)")
            ok = False
    except SystemExit as e:
        print(f"   FAIL {e}")
        ok = False

    print("3) Agent profile")
    cfgfile = Path(os.environ.get("DATABRICKS_CONFIG_FILE") or
                   Path(os.environ.get("DBX_GUARD_HOME") or Path.home()) / ".databrickscfg")
    import configparser
    cp = configparser.ConfigParser()
    try:
        cp.read(cfgfile)
        host = cp.get("agent", "host", fallback="")
        good = host.startswith("http://127.0.0.1:") or host.startswith("http://localhost:")
        print(f"   {'ok  ' if good else 'FAIL'} [agent] host = {host or '(missing)'} in {cfgfile}")
        ok &= good
    except Exception as e:
        print(f"   FAIL cannot read {cfgfile}: {e}")
        ok = False
    print("RESULT: " + ("ALL CHECKS PASSED" if ok else "PROBLEMS FOUND"))
    return 0 if ok else 1


def _utf8_console() -> None:
    """Windows consoles default to cp1252; never let printing a message crash a guard."""
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
        except Exception:
            pass


def main(argv=None) -> int:
    _utf8_console()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("install")
    i.add_argument("--upstream-profile", default="DEFAULT", help="your real OAuth U2M profile")
    i.add_argument("--port", type=int, default=8787)
    i.add_argument("--python", help="interpreter for the service (default: this one)")
    i.add_argument("--dry-run", action="store_true")
    for name in ("uninstall", "restart"):
        x = sub.add_parser(name)
        x.add_argument("--dry-run", action="store_true")
    sub.add_parser("status")
    sub.add_parser("doctor")
    args = ap.parse_args(argv)
    return {"install": cmd_install, "uninstall": cmd_uninstall, "restart": cmd_restart,
            "status": cmd_status, "doctor": cmd_doctor}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
